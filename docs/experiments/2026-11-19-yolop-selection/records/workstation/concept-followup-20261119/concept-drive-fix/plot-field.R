library(jsonlite)
a <- fromJSON("1550-speed-trace.json")
png("1550-speed.png", width=1060, height=540, res=110, type="cairo")
par(mar=c(4.3,4.5,3,1), las=1, mgp=c(2.8,.75,0), bty="l")
plot(0, type="n", xlim=range(a$wheel_speed[,1]), ylim=c(-.1,4.35), xlab="Elapsed time in the 15:50 recording (s)", ylab="Speed (m/s)", main="Concept field run   |   19 Nov 2026, 15:50 JST")
abline(h=seq(0,4,.5), col="#e2e6e8", lwd=.6)
lines(a$gate_limit,type="s",col="#79548A",lty=2,lwd=2.5)
lines(a$target,type="s",col="#AA5D1E",lty=3,lwd=3)
lines(a$motor_input,type="s",col="#3869A1",lwd=1.7)
lines(a$wheel_speed,col="#09816B",lwd=2)
legend("topleft",inset=c(.01,.10),legend=c("Gate limit","Planner target","Motor speed request","Measured wheel mean"),col=c("#79548A","#AA5D1E","#3869A1","#09816B"),lty=c(2,3,1,1),lwd=2, bg="white",box.col="#e2e6e8",cex=.85)
dev.off()
